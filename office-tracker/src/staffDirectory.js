function staffNameKey(name) {
  return String(name ?? '')
    .trim()
    .replace(/\s+/g, ' ')
    .toLowerCase();
}

const EMAIL_BY_NAME = new Map(
  TRANSPORTATION_STAFF.map((person) => [staffNameKey(person.name), person.email])
);

// The published address for this display name, or '' when the directory has no such person.
export function directoryEmail(name) {
  return EMAIL_BY_NAME.get(staffNameKey(name)) || '';
}

function joinedName(driver) {
  return [driver?.firstName, driver?.lastName]
    .map((part) => String(part ?? '').trim())
    .filter(Boolean)
    .join(' ');
}

// Keep a directory name on the published address.
export function lockDirectoryEmail(driver) {
  if (!driver || typeof driver !== 'object') return driver;
  const email = directoryEmail(driver.name) || directoryEmail(joinedName(driver));
  if (!email || driver.email === email) return driver;
  return { ...driver, email };
}

export function lockDirectoryEmails(drivers) {
  if (!Array.isArray(drivers)) return drivers;
  return drivers.map((driver) => lockDirectoryEmail(driver));
}
