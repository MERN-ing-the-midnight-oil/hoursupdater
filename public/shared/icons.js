/**
 * @param {string} name
 * @param {{ className?: string, decorative?: boolean, title?: string }} [opts]
 * @returns {SVGSVGElement}
 */
export function createIcon(name, opts = {}) {
  const { className = 'icon', decorative = true, title } = opts;
  const paths = PATHS[name];
  if (!paths) {
    console.warn(`Unknown icon: ${name}`);
    return document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  }

  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.classList.add(...className.split(/\s+/).filter(Boolean));
  svg.dataset.iconName = name;
  svg.innerHTML = paths;

  if (decorative) {
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
  } else if (title) {
    svg.setAttribute('role', 'img');
    svg.setAttribute('aria-label', title);
  }

  return svg;
}

/**
 * Prepend an icon to an element (idempotent).
 * @param {HTMLElement} el
 * @param {string} name
 */
export function prependIcon(el, name) {
  if (el.querySelector(':scope > .icon')) return;
  el.prepend(createIcon(name));
  el.classList.add('with-icon');
}

/**
 * Replace element contents with icon + text (for buttons / simple labels).
 * @param {HTMLElement} el
 * @param {string} name
 * @param {string} text
 */
export function setLabeledIcon(el, name, text) {
  el.replaceChildren(createIcon(name), document.createTextNode(text));
  el.classList.add('with-icon');
}

/**
 * Scan [data-icon] hosts and prepend icons.
 * @param {ParentNode} [root=document]
 */
export function enhanceIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (!(el instanceof HTMLElement)) continue;
    const name = el.dataset.icon;
    if (!name) continue;
    prependIcon(el, name);
  }
}
